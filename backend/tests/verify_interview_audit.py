import os
import sys

from app.database import SessionLocal
from app.models.company import Company, CompanyProfile
from app.models.interview import InterviewSession, InterviewQA

db = SessionLocal()

print("=" * 60)
print("INTERVIEW SESSIONS")
print("=" * 60)
sessions = db.query(InterviewSession).all()
for s in sessions:
    total_q = db.query(InterviewQA).filter(InterviewQA.session_id == s.id).count()
    ans_q = db.query(InterviewQA).filter(InterviewQA.session_id == s.id, InterviewQA.is_answered == True).count()
    followup_ans = db.query(InterviewQA).filter(InterviewQA.session_id == s.id, InterviewQA.follow_up_answer.isnot(None)).count()
    takeaway_count = db.query(InterviewQA).filter(InterviewQA.session_id == s.id, InterviewQA.strategic_takeaway.isnot(None)).count()
    print(f"Session: {s.id}")
    print(f"  Company: {s.company_id}")
    print(f"  Status: {s.status}")
    print(f"  Progress: {s.current_question_index} / {s.total_questions}")
    print(f"  Created: {s.created_at}")
    print(f"  Completed: {s.completed_at}")
    print(f"  Questions: {total_q}, Main Answers: {ans_q}, Follow-up Answers: {followup_ans}, Strategic Takeaways: {takeaway_count}")
    print("-" * 40)

print("\n" + "=" * 60)
print("SESSION_MU_01 DETAILS (ALL 10 Q&A)")
print("=" * 60)
mu_qas = db.query(InterviewQA).filter(InterviewQA.session_id == "session_mu_01").order_by(InterviewQA.question_number).all()
for qa in mu_qas:
    print(f"Q{qa.question_number} [{qa.category}]: {qa.question_text}")
    print(f"  Answer: {qa.answer_text}")
    print(f"  Follow-up Q: {qa.follow_up_question}")
    print(f"  Follow-up A: {qa.follow_up_answer}")
    print(f"  Strategic Takeaway: {qa.strategic_takeaway}")
    print(f"  Is Answered: {qa.is_answered}, Answered At: {qa.answered_at}")
    print("-" * 40)

print("\n" + "=" * 60)
print("COMPANY PROFILE (meetuniversity)")
print("=" * 60)
comp = db.query(Company).filter(Company.id == "meetuniversity").first()
prof = db.query(CompanyProfile).filter(CompanyProfile.company_id == "meetuniversity").first()
if comp:
    print(f"Company: {comp.name} ({comp.id})")
    print(f"Industry: {comp.industry}")
    print(f"Description: {comp.description}")
if prof:
    print(f"Business Model: {prof.business_model}")
    print(f"Value Proposition: {prof.value_proposition}")
    print(f"Pricing Tier: {prof.pricing_tier}")
    print(f"Strategic Priorities: {prof.strategic_priorities}")
    print(f"Key Differentiators: {prof.key_differentiators}")
    print(f"Risks & Challenges: {prof.risks_and_challenges}")
    print(f"Tech Stack Summary: {prof.tech_stack_summary}")
    print(f"Generated By: {prof.generated_by}")
else:
    print("NO PROFILE FOUND")

db.close()
